const mongoose = require('mongoose');
const { integer, nonEmptyArray, uniqueItems, nonEmptyStrings } = require('./validators');

const MAX_ROWS = 26; // rows are lettered A-Z
const MAX_SEATS_PER_ROW = 50;

// rows = 2, seatsPerRow = 3 -> ['A1', 'A2', 'A3', 'B1', 'B2', 'B3']
function generateSeatLabels(rows, seatsPerRow) {
  const labels = [];
  for (let row = 0; row < rows; row += 1) {
    const letter = String.fromCharCode(65 + row);
    for (let seat = 1; seat <= seatsPerRow; seat += 1) {
      labels.push(`${letter}${seat}`);
    }
  }
  return labels;
}

const auditoriumSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, unique: true, trim: true },
    rows: {
      type: Number,
      required: true,
      min: [1, 'rows must be at least 1'],
      max: [MAX_ROWS, `rows must be at most ${MAX_ROWS}`],
      validate: integer,
    },
    seatsPerRow: {
      type: Number,
      required: true,
      min: [1, 'seatsPerRow must be at least 1'],
      max: [MAX_SEATS_PER_ROW, `seatsPerRow must be at most ${MAX_SEATS_PER_ROW}`],
      validate: integer,
    },
    // Seats that cannot be booked in any showing here (broken, reserved for wheelchairs ...).
    blockedSeats: { type: [String], default: [] },
    // Always generated by the server from rows and seatsPerRow.
    seatLabels: {
      type: [String],
      required: true,
      validate: [
        nonEmptyArray,
        uniqueItems,
        nonEmptyStrings,
        {
          validator(value) {
            return value.length === this.rows * this.seatsPerRow;
          },
          message: 'seatLabels must match rows x seatsPerRow',
        },
      ],
    },
    isActive: { type: Boolean, default: true },
    // Bumped on every schedule change in this auditorium (see services/showtimes.js). Writing the
    // auditorium inside the transaction makes two concurrent schedule changes conflict, so they
    // run one after the other and the second one sees the first one's showtime.
    scheduleRevision: { type: Number, default: 0 },
  },
  { timestamps: true },
);

// Clients never choose seat labels. Regenerate whenever the layout is new or changed.
auditoriumSchema.pre('validate', function regenerateSeatLabels(next) {
  const layoutChanged = this.isNew || this.isModified('rows') || this.isModified('seatsPerRow');
  if (layoutChanged && Number.isInteger(this.rows) && Number.isInteger(this.seatsPerRow)
    && this.rows >= 1 && this.rows <= MAX_ROWS
    && this.seatsPerRow >= 1 && this.seatsPerRow <= MAX_SEATS_PER_ROW) {
    this.seatLabels = generateSeatLabels(this.rows, this.seatsPerRow);
    // A blocked seat that the new layout no longer has cannot stay blocked.
    this.blockedSeats = (this.blockedSeats || []).filter((label) => this.seatLabels.includes(label));
  }
  next();
});

auditoriumSchema.statics.generateSeatLabels = generateSeatLabels;

module.exports = mongoose.model('Auditorium', auditoriumSchema);
